using System;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Singleton.Generator
{
    /// <summary>
    /// How the instance of a singleton is first made.
    /// </summary>
    internal enum SingletonInstance
    {
        /// <summary>By the parameterless constructor of the type.</summary>
        Newable,

        /// <summary>By a creator which the attribute named.</summary>
        Creator,

        /// <summary>By finding the node Godot made, or by making one under the root of the scene tree.</summary>
        Node,

        /// <summary>By finding the node Godot made, or by loading a scene and instantiating it.</summary>
        AssetNode,

        /// <summary>By loading a resource.</summary>
        AssetResource
    }

    /// <summary>
    /// One type which asked for a singleton, with everything the half which is generated for it is written from.
    /// </summary>
    internal sealed class SingletonTarget
    {
        /// <summary>
        /// Makes a target of a type which asked for a singleton.
        /// </summary>
        /// <param name="type">The type which asked for the singleton.</param>
        /// <param name="instance">How the instance is first made.</param>
        public SingletonTarget(INamedTypeSymbol type, SingletonInstance instance)
        {
            Type = type;
            Instance = instance;
        }

        /// <summary>The type which asked for the singleton.</summary>
        public INamedTypeSymbol Type { get; }

        /// <summary>How the instance is first made.</summary>
        public SingletonInstance Instance { get; }

        /// <summary>Whether the node is to be kept across a change of scene.</summary>
        public bool Persistent { get; set; }

        /// <summary>Whether the instance may be the node which is already in the scene tree.</summary>
        public bool Reusable { get; set; }

        /// <summary>
        /// Whether a type which this one derives from asked for a singleton of its own, so that what is written here
        /// hides what is written there rather than standing beside it.
        /// </summary>
        public bool Hides { get; set; }

        /// <summary>The path which an asset is loaded by.</summary>
        public string? AssetPath { get; set; }

        /// <summary>The creator which makes the instance.</summary>
        public INamedTypeSymbol? Creator { get; set; }

        /// <summary>The constructor of the creator which the arguments are fitted to.</summary>
        public IMethodSymbol? CreatorConstructor { get; set; }

        /// <summary>The arguments which the attribute named the creator with, one to each parameter of the constructor.</summary>
        public List<TypedConstant> CreatorConstructorArguments { get; } = new();
    }

    /// <summary>
    /// Writes the half of a singleton which holds the field and the property.
    /// </summary>
    /// <remarks>
    /// Everything written here is named in full, so that the file stands on its own: it is compiled beside
    /// <c>using</c> directives which were written for another file, and a name it takes from them would be a name it
    /// takes by accident.
    /// </remarks>
    internal static class SingletonEmitter
    {
        /// <summary>What is written at the top of the file.</summary>
        private const string HEADER =
            "// <auto-generated>\n" +
            "//     This file was generated by the Singleton source generator.\n" +
            "//     It is written again on every compilation, so changes to it are lost.\n" +
            "// </auto-generated>\n" +
            "#nullable enable\n";

        /// <summary>What a node which is held is asked whether it is still there by.</summary>
        private const string ALIVE = "global::Singleton.Runtime.SingletonRuntime.Alive";

        /// <summary>
        /// Write the generated half of a singleton.
        /// </summary>
        /// <param name="target">The singleton.</param>
        /// <param name="arguments">What the arguments of a creator are written by.</param>
        /// <returns>The file.</returns>
        public static string Emit(SingletonTarget target, ArgumentRenderer arguments)
        {
            var builder = new StringBuilder(HEADER);
            var type = target.Type;
            var indent = string.Empty;

            builder.AppendLine();

            var wrapped = !type.ContainingNamespace.IsGlobalNamespace;
            if (wrapped)
            {
                builder.Append("namespace ").AppendLine(type.ContainingNamespace.ToDisplayString());
                builder.AppendLine("{");
                indent = "    ";
            }

            // Every type a singleton was declared inside of is declared again here, because the generated half is a
            // second declaration of the singleton and not a member inside the first one.
            var containers = Containers(type);
            foreach (var container in containers)
            {
                if (SymbolEqualityComparer.Default.Equals(container, type)) continue;

                builder.Append(indent).AppendLine(Declaration(container));
                builder.Append(indent).AppendLine("{");
                indent += "    ";
            }

            builder.Append(indent).AppendLine(Declaration(type));

            // A singleton which the compiler reads as a static interface is one which can be read through a type
            // argument alone, which is what the interface is for. Godot builds with a language which has static
            // interface members, so this is written without a guard.
            builder.Append(indent).Append("    : global::Singleton.Runtime.ISingleton<").Append(type.Name).AppendLine(">");

            builder.Append(indent).AppendLine("{");
            indent += "    ";

            var qualified = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            builder.Append(indent).AppendLine("/// <summary>The instance, which is null until one is made.</summary>");
            builder.Append(indent).Append("private static ").Append(qualified).AppendLine("? s_Instance;");
            builder.AppendLine();
            builder.Append(indent).Append("/// <summary>").Append(Summary(target)).AppendLine("</summary>");
            builder.Append(indent).Append(Modifiers(target)).Append(qualified).AppendLine(" Instance");
            builder.Append(indent).AppendLine("{");
            builder.Append(indent).AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            builder.Append(indent).AppendLine("    get");
            builder.Append(indent).AppendLine("    {");

            WriteBody(builder, indent + "        ", target, arguments, qualified);

            builder.Append(indent).AppendLine("    }");
            builder.Append(indent).AppendLine("}");

            // What a caller which must not bring a singleton into being reads: the property makes the instance where
            // there is none, and a message which may run before the one which would have made it is a message which
            // cannot ask the property whether there is one at all.
            builder.AppendLine();
            builder.Append(indent).AppendLine("/// <summary>The instance of the singleton where there is one, which is answered without making one.</summary>");
            builder.Append(indent).AppendLine("/// <param name=\"instance\">The instance, where there is one.</param>");
            builder.Append(indent).AppendLine("/// <returns>Whether there is one.</returns>");
            builder.Append(indent).Append("public static bool TryGetInstance(out ").Append(qualified).AppendLine(" instance)");
            builder.Append(indent).AppendLine("{");

            if (Freed(target))
            {
                // A node which was freed is held by the field as a value which throws when it is read, so whether there
                // is one is asked the same way the property asks it, and the field is given up here as well rather than
                // handed to a caller which would then read it.
                builder.Append(indent).Append("    if (s_Instance != null && !").Append(ALIVE).AppendLine("(s_Instance)) s_Instance = null;");
            }

            builder.Append(indent).AppendLine("    instance = s_Instance!;");
            builder.Append(indent).AppendLine("    return instance != null;");
            builder.Append(indent).AppendLine("}");

            // The brace of a declaration is written one step further out than what it holds, so every declaration is
            // closed by stepping out and then writing.
            indent = Outdent(indent);
            builder.Append(indent).AppendLine("}");

            for (var index = containers.Count - 2; index >= 0; index--)
            {
                indent = Outdent(indent);
                builder.Append(indent).AppendLine("}");
            }

            if (wrapped)
            {
                indent = Outdent(indent);
                builder.Append(indent).AppendLine("}");
            }

            return builder.ToString();
        }

        /// <summary>
        /// Whether the instance of a singleton is one Godot may take away, which is the case for a node.
        /// </summary>
        /// <param name="target">The singleton.</param>
        /// <returns>Whether it is.</returns>
        private static bool Freed(SingletonTarget target) =>
            target.Instance is SingletonInstance.Node or SingletonInstance.AssetNode;

        /// <summary>
        /// Step an indentation out by one declaration.
        /// </summary>
        /// <param name="indent">The indentation.</param>
        /// <returns>The indentation of the declaration which holds the type.</returns>
        private static string Outdent(string indent) => indent.Substring(0, indent.Length - 4);

        /// <summary>
        /// What the property of the generated half is declared with.
        /// </summary>
        /// <remarks>
        /// A member of a type which is declared beside a member of the same name of a type it derives from hides it,
        /// and a compiler which reads that as an accident says so: what is written here says which of the two it is, so
        /// that a singleton which derives from a singleton is one a reader is told about rather than one a warning is
        /// raised over.<para/>
        /// What the method is declared with is not this, because a method which answers with the type it is declared in
        /// is one no base type declares alike - the argument it is answered with is a type of its own - so it is an
        /// overload of the one the base type declares rather than a member which hides it, and <c>new</c> on it is what
        /// the compiler warns about.
        /// </remarks>
        /// <param name="target">The singleton.</param>
        /// <returns>The modifiers of the declaration.</returns>
        private static string Modifiers(SingletonTarget target) => target.Hides ? "public new static " : "public static ";

        /// <summary>
        /// What the property of a singleton is documented as.
        /// </summary>
        /// <remarks>
        /// A reader of the generated half of a type is a reader who went looking for what the property does, and what
        /// it does is not one thing: a node is looked for before anything is made where the type asked to be reusable,
        /// and a type which an asset is loaded from is loaded. What is written is therefore what this singleton makes
        /// its instance with rather than one sentence for every one of them, which would be a sentence this one is not.
        /// </remarks>
        /// <param name="target">The singleton.</param>
        /// <returns>The summary of the property.</returns>
        private static string Summary(SingletonTarget target) => target.Instance switch
        {
            SingletonInstance.Newable =>
                "The instance of the singleton, which the constructor of the type makes the first time it is read.",
            SingletonInstance.Creator =>
                "The instance of the singleton, which the creator the attribute named makes the first time it is read.",
            SingletonInstance.Node => target.Reusable
                ? "The instance of the singleton, which is looked for in the scene tree and made under the root where there is none."
                : "The instance of the singleton, which is made under the root of the scene tree the first time it is read.",
            SingletonInstance.AssetNode => target.Reusable
                ? "The instance of the singleton, which is looked for in the scene tree and loaded from the scene where there is none."
                : "The instance of the singleton, which is loaded from the scene the first time it is read.",
            SingletonInstance.AssetResource =>
                "The instance of the singleton, which is loaded from the resource the first time it is read.",
            // A member of the enumeration which no arm above names is one this was not written for, and the sentence it
            // is given is the one which is true of every singleton rather than of the one which makes it.
            _ =>
                "The instance of the singleton."
        };

        /// <summary>
        /// Write the body of the getter, which makes the instance where there is none and returns it.
        /// </summary>
        /// <param name="builder">The file.</param>
        /// <param name="indent">What the body is indented with.</param>
        /// <param name="target">The singleton.</param>
        /// <param name="arguments">What the arguments of a creator are written by.</param>
        /// <param name="qualified">The name of the type, written in full.</param>
        private static void WriteBody(StringBuilder builder, string indent, SingletonTarget target,
                                      ArgumentRenderer arguments, string qualified)
        {
            // A node is the one instance Godot takes away without asking the singleton about it, so whether the field
            // holds one is asked twice: that it is not nothing, and that what it holds is still there. A field which
            // holds a node which was freed is one which answers every read with a value that throws.
            var condition = Freed(target)
                ? "s_Instance == null || !" + ALIVE + "(s_Instance)"
                : "s_Instance == null";

            switch (target.Instance)
            {
                case SingletonInstance.Newable:
                    WriteMake(builder, indent, target, qualified, condition, body =>
                        builder.Append(body).Append("s_Instance = new ").Append(qualified).AppendLine("();"));
                    break;

                case SingletonInstance.Creator:
                    var creator = target.Creator!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    WriteMake(builder, indent, target, qualified, condition, body =>
                    {
                        builder.Append(body).Append("s_Instance = new ").Append(creator).Append('(');
                        WriteArguments(builder, target, arguments);
                        builder.AppendLine(").Create();");
                    });
                    break;

                case SingletonInstance.Node:
                    WriteMake(builder, indent, target, qualified, condition, body => WriteMakeNode(builder, body, qualified));
                    break;

                case SingletonInstance.AssetNode:
                    WriteMake(builder, indent, target, qualified, condition, body => WriteLoadNode(builder, body, target, qualified));
                    break;

                case SingletonInstance.AssetResource:
                    WriteMake(builder, indent, target, qualified, condition, body => WriteLoadResource(builder, body, target, qualified));
                    break;
            }

            builder.Append(indent).AppendLine("return s_Instance!;");
        }

        /// <summary>
        /// Write the guard which decides that an instance has to be made, looking for the node which is already in the
        /// tree first where the type asked to be reusable.
        /// </summary>
        /// <remarks>
        /// Both the search and the guard which follows it are written only for a type which asked for them: a type
        /// which asked for nothing never searched, so the second test would be one which is true every time it is
        /// reached, and a reader would be given a test which decides nothing.
        /// </remarks>
        /// <param name="builder">The file.</param>
        /// <param name="indent">What the body is indented with.</param>
        /// <param name="target">The singleton.</param>
        /// <param name="qualified">The name of the type, written in full.</param>
        /// <param name="condition">What is asked of the field to tell that an instance has to be made.</param>
        /// <param name="make">What writes what is done where neither the field nor the search answered with one.</param>
        private static void WriteMake(StringBuilder builder, string indent, SingletonTarget target, string qualified,
                                      string condition, Action<string> make)
        {
            builder.Append(indent).Append("if (").Append(condition).AppendLine(")");
            builder.Append(indent).AppendLine("{");

            var body = indent + "    ";

            // A node which was freed is held as a value which throws when it is read, so the field is given up before
            // anything is asked of it again. The weaver clears it on the way out of the tree, and this is what covers a
            // node which was freed without the notification being run at all.
            if (Freed(target)) builder.Append(body).AppendLine("s_Instance = null;");

            if (target.Reusable)
            {
                builder.Append(body).Append("s_Instance = global::Singleton.Runtime.SingletonRuntime.Search<")
                       .Append(qualified).AppendLine(">();");
                builder.Append(body).AppendLine("if (s_Instance == null)");
                builder.Append(body).AppendLine("{");
                body += "    ";
            }

            make(body);

            if (target.Reusable) builder.Append(indent).AppendLine("    }");
            builder.Append(indent).AppendLine("}");
        }

        /// <summary>
        /// Write what makes a node where there is none: one of the type itself, put under the root of the scene tree so
        /// that it is a part of no scene and outlives the one which is current.
        /// </summary>
        /// <param name="builder">The file.</param>
        /// <param name="indent">What the body is indented with.</param>
        /// <param name="qualified">The name of the type, written in full.</param>
        private static void WriteMakeNode(StringBuilder builder, string indent, string qualified)
        {
            builder.Append(indent).Append("var node = new ").Append(qualified).AppendLine("();");
            builder.Append(indent).AppendLine("if (global::Godot.Engine.GetMainLoop() is global::Godot.SceneTree tree && tree.Root != null) tree.Root.AddChild(node);");

            // A node which was added is one the notification of the singleton put in the field already, and a node which
            // was not - there is no scene tree to add it to - is one nothing else will.
            builder.Append(indent).AppendLine("if (s_Instance == null) s_Instance = node;");
        }

        /// <summary>
        /// Write what loads a scene and instantiates it where there is no node already.
        /// </summary>
        /// <param name="builder">The file.</param>
        /// <param name="indent">What the body is indented with.</param>
        /// <param name="target">The singleton.</param>
        /// <param name="qualified">The name of the type, written in full.</param>
        private static void WriteLoadNode(StringBuilder builder, string indent, SingletonTarget target, string qualified)
        {
            WriteAssetPath(builder, indent, target.AssetPath!);
            builder.Append(indent).AppendLine("var scene = global::Godot.ResourceLoader.Load<global::Godot.PackedScene>(assetPath);");
            builder.Append(indent).AppendLine("if (scene == null) throw new global::System.ArgumentException($\"Failed to load the singleton scene at path: {assetPath}\");");
            builder.Append(indent).AppendLine("var node = scene.Instantiate();");
            builder.Append(indent).AppendLine("if (global::Godot.Engine.GetMainLoop() is global::Godot.SceneTree tree && tree.Root != null) tree.Root.AddChild(node);");
            builder.Append(indent).Append("if (s_Instance == null) s_Instance = node as ").Append(qualified).AppendLine(";");

            // A scene whose root is not the type is a scene which was named for the wrong singleton, and answering with
            // nothing would be a singleton which is never there for a reason nobody is told.
            builder.Append(indent).Append("if (s_Instance == null) throw new global::System.ArgumentException($\"The scene at {assetPath} holds no ").Append(target.Type.Name).AppendLine(".\");");
        }

        /// <summary>
        /// Write what loads a resource where there is none.
        /// </summary>
        /// <param name="builder">The file.</param>
        /// <param name="indent">What the body is indented with.</param>
        /// <param name="target">The singleton.</param>
        /// <param name="qualified">The name of the type, written in full.</param>
        private static void WriteLoadResource(StringBuilder builder, string indent, SingletonTarget target, string qualified)
        {
            WriteAssetPath(builder, indent, target.AssetPath!);
            builder.Append(indent).Append("s_Instance = global::Godot.ResourceLoader.Load<").Append(qualified).AppendLine(">(assetPath);");
            builder.Append(indent).AppendLine("if (s_Instance == null) throw new global::System.ArgumentException($\"Failed to load the singleton resource at path: {assetPath}\");");
        }

        /// <summary>
        /// Write the arguments which the constructor of a creator is called with.
        /// </summary>
        /// <param name="builder">The file.</param>
        /// <param name="target">The singleton.</param>
        /// <param name="arguments">What an argument is written by.</param>
        private static void WriteArguments(StringBuilder builder, SingletonTarget target, ArgumentRenderer arguments)
        {
            var parameters = target.CreatorConstructor!.Parameters;
            for (var index = 0; index < parameters.Length; index++)
            {
                if (index > 0) builder.Append(", ");
                builder.Append(arguments.Render(target.CreatorConstructorArguments[index]));
            }
        }

        /// <summary>
        /// Write the asset path as a constant of the getter.
        /// </summary>
        /// <param name="builder">The file.</param>
        /// <param name="indent">What the constant is indented with.</param>
        /// <param name="path">The path.</param>
        private static void WriteAssetPath(StringBuilder builder, string indent, string path)
        {
            builder.Append(indent).Append("const string assetPath = ")
                   .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(path, quote: true))
                   .AppendLine(";");
        }

        /// <summary>
        /// Read the declarations which hold a type, from the outermost one to the declaration of the type itself.
        /// </summary>
        /// <param name="type">The type.</param>
        /// <returns>The declarations.</returns>
        private static List<INamedTypeSymbol> Containers(INamedTypeSymbol type)
        {
            var containers = new List<INamedTypeSymbol>();
            for (var current = type; current != null; current = current.ContainingType) containers.Add(current);
            containers.Reverse();
            return containers;
        }

        /// <summary>
        /// Write the declaration of a type, without what a partial declaration may leave out.
        /// </summary>
        /// <param name="type">The type.</param>
        /// <returns>The declaration.</returns>
        private static string Declaration(INamedTypeSymbol type)
        {
            var keyword = type.TypeKind switch
            {
                TypeKind.Struct => "struct",
                TypeKind.Interface => "interface",
                _ => type.IsRecord ? "record" : "class"
            };

            return $"{Accessibility(type)} partial {keyword} {type.Name}";
        }

        /// <summary>
        /// Write the accessibility which a type declared, and which a partial declaration of it has to agree with.
        /// </summary>
        /// <param name="type">The type.</param>
        /// <returns>The accessibility.</returns>
        private static string Accessibility(INamedTypeSymbol type) => type.DeclaredAccessibility switch
        {
            Microsoft.CodeAnalysis.Accessibility.Public => "public",
            Microsoft.CodeAnalysis.Accessibility.Private => "private",
            Microsoft.CodeAnalysis.Accessibility.Protected => "protected",
            Microsoft.CodeAnalysis.Accessibility.ProtectedOrInternal => "protected internal",
            Microsoft.CodeAnalysis.Accessibility.ProtectedAndInternal => "private protected",
            _ => "internal"
        };
    }
}
